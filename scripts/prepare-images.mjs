// Copies the owner's project photos from "Brand Info/Photos" into public/images/projects,
// in the order chosen in CLAUDE.md §2: auto-rotated, resized, EXIF/GPS stripped (client privacy).
// Also writes content/project-images.ts (dimensions + blur placeholders).
// Filenames carry a content hash (01-1a2b3c4d.jpg) so a replaced photo gets a new URL and is never stuck in a cache.
// Run: npm run images
import { createHash } from "node:crypto";
import { mkdir, readdir, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";

const SRC = "Brand Info/Photos";
const OUT = "public/images/projects";
const MAX = 2048;
const MIN_LONG_SIDE = 1200;

// Filenames are matched by their leading prefix. First entry = cover.
const PROJECTS = [
  { slug: "pompage-3-kwc-2026", folder: "Project 1", order: ["654698536", "656189013", "657328037", "656740107"] },
  { slug: "pompage-5-5-kwc-2025", folder: "Project 2", order: ["599043925", "598575630", "598570735", "598557895"] },
  { slug: "residentiel-3-1-kwc-2025", folder: "Project 3", order: ["494736991", "493992939", "495062124"] },
  { slug: "pompage-7-2-kwc-2024", folder: "Project 4", order: ["489310625", "489009099", "489365990", "489087727"] },
  { slug: "residentiel-3-2-kwc-2023", folder: "Project 5", order: ["475319129", "475374982", "475120750"] },
  { slug: "residentiel-4-kwc-2022-12", folder: "Project 6", order: ["475191291", "474916218_1655116238", "474916218_1655116265", "475079968"] },
  { slug: "residentiel-4-kwc-2022-11", folder: "Project 7", order: ["475254738", "475281206", "474995355", "475037064"] },
  { slug: "residentiel-3-3-kwc-2021", folder: "Project 8", order: ["177499778", "178748725", "178427571", "178359218"] },
  { slug: "residentiel-2-5-kwc-2021", folder: "Project 9", order: ["173651877", "173564225", "172758905", "173111504", "172373020", "173223254"] },
  { slug: "residentiel-2-2-kwc-2020", folder: "Project 10", order: ["106530683", "106353140", "106371408"] },
];

await rm(OUT, { recursive: true, force: true });
const manifest = {};

for (const p of PROJECTS) {
  const files = (await readdir(path.join(SRC, p.folder))).filter((f) => /\.jpe?g$/i.test(f));
  const dir = path.join(OUT, p.slug);
  await mkdir(dir, { recursive: true });
  manifest[p.slug] = [];

  for (const [i, prefix] of p.order.entries()) {
    const file = files.find((f) => f.startsWith(prefix));
    if (!file) throw new Error(`${p.folder}: no file starting with ${prefix}`);
    const pipeline = sharp(path.join(SRC, p.folder, file)).rotate();
    const meta = await pipeline.metadata();
    const longSide = Math.max(meta.width ?? 0, meta.height ?? 0);
    // Small sources (e.g. Project 4's 590 px cover) are upscaled once with Lanczos + a light sharpen,
    // which looks smoother than the browser stretching them. It adds no real detail.
    const resized =
      longSide < MIN_LONG_SIDE
        ? pipeline.clone().resize({ width: MIN_LONG_SIDE, height: MIN_LONG_SIDE, fit: "inside", kernel: "lanczos3" }).sharpen({ sigma: 0.6 })
        : pipeline.clone().resize({ width: MAX, height: MAX, fit: "inside", withoutEnlargement: true });
    // Re-encoding drops all metadata (sharp keeps none unless .withMetadata() is called).
    const { data, info } = await resized.jpeg({ quality: 82, mozjpeg: true }).toBuffer({ resolveWithObject: true });
    const { width, height } = info;
    const hash = createHash("sha256").update(data).digest("hex").slice(0, 8);
    const name = `${String(i + 1).padStart(2, "0")}-${hash}.jpg`;
    await writeFile(path.join(dir, name), data);
    if (longSide < MIN_LONG_SIDE) console.log(`  upscaled ${file} (${meta.width}×${meta.height} → ${width}×${height})`);
    const blur = await pipeline.clone().resize(12, 12, { fit: "inside" }).webp({ quality: 40 }).toBuffer();
    manifest[p.slug].push({
      src: `/images/projects/${p.slug}/${name}`,
      width,
      height,
      blurDataURL: `data:image/webp;base64,${blur.toString("base64")}`,
    });
  }
  console.log(`${p.slug}: ${p.order.length} images`);
}

const ts = `// Generated by scripts/prepare-images.mjs. Do not edit by hand.
export type ProjectImage = { src: string; width: number; height: number; blurDataURL: string };

export const projectImages: Record<string, ProjectImage[]> = ${JSON.stringify(manifest, null, 2)};
`;
await writeFile("content/project-images.ts", ts);
console.log("content/project-images.ts written");
